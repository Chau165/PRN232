 render(<MemoryRouter><BookingIdentityForm {...props()}/></MemoryRouter>);fireEvent.click(screen.getByRole("button",{name:"Chuẩn bị hồ sơ CCCD"}));await screen.findByText("Bạn — Người đứng tên dự kiến")
