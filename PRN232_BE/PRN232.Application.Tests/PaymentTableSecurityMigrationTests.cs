using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Npgsql;
using PRN232.Infrastructure.Data;
using PRN232.Infrastructure.Migrations;
using Xunit;

namespace PRN232.Application.Tests;

public class PaymentTableSecurityMigrationTests
{
    private static readonly Dictionary<string, string> Tables = new()
    {
        ["PaymentRequests"] = "PaymentRequestId", ["PaymentReviewCases"] = "PaymentReviewCaseId",
        ["PaymentWebhookReceipts"] = "PaymentWebhookReceiptId", ["BookingRefundRequests"] = "BookingRefundRequestId",
        ["PayoutAttempts"] = "PayoutAttemptId", ["BookingRefunds"] = "BookingRefundId"
    };
    [Fact]
    public void Script_secures_all_six_tables_without_changing_business_data_or_reopening_on_rollback()
    {
        using var db = new AppDbContext(new DbContextOptionsBuilder<AppDbContext>()
            .UseNpgsql("Host=localhost;Database=unused;Username=test;Password=test").Options);
        const string before = "20261113075616_AddBookingRefundLedger";
        const string target = "20261113103807_SecurePaymentTables";
        Assert.Contains(target, db.Database.GetMigrations());
        var sql = db.GetService<IMigrator>().GenerateScript(before, target);
        foreach (var table in Tables.Keys)
        {
            Assert.Contains($"ALTER TABLE public.\"{table}\" ENABLE ROW LEVEL SECURITY", sql);
            Assert.Contains($"REVOKE ALL PRIVILEGES ON TABLE public.\"{table}\" FROM PUBLIC", sql);
        }
        Assert.Contains("rolname = api_role", sql);
        Assert.Contains("'anon', 'authenticated', 'service_role'", sql);
        Assert.Contains("REVOKE ALL PRIVILEGES ON SEQUENCE", sql);
        Assert.Contains("has_any_column_privilege", sql);
        Assert.DoesNotContain("FORCE ROW LEVEL SECURITY", sql);
        Assert.DoesNotContain("CREATE POLICY", sql);
        Assert.DoesNotContain("DROP TABLE", sql);
        Assert.DoesNotContain("UPDATE public.", sql);
        Assert.Empty(new SecurePaymentTables().DownOperations);
        Assert.DoesNotContain("DISABLE ROW LEVEL SECURITY", db.GetService<IMigrator>().GenerateScript(target, before));
    }

    [Phase31BPostgreSqlFact]
    public async Task PostgreSQL_blocks_api_roles_keeps_owner_access_and_preserves_rows_with_or_without_supabase_roles()
    {
        var server = new NpgsqlConnectionStringBuilder(Environment.GetEnvironmentVariable("PRN232_MIGRATION_TEST_POSTGRES_CONNECTION"))
            { Pooling = false, Timeout = 5, CommandTimeout = 30 };
        Assert.Contains(server.Host, new[] { "localhost", "127.0.0.1", "::1" });
        Assert.Equal(55432, server.Port); Assert.Equal("postgres", server.Database);
        Assert.Equal("PRN232-Phase31B-Isolated-Test", server.ApplicationName);
        var name = "prn232_payment_security_" + Guid.NewGuid().ToString("N");
        await using var admin = new NpgsqlConnection(server.ConnectionString); await admin.OpenAsync();
        async Task Admin(string sql) { await using var c = new NpgsqlCommand(sql, admin); await c.ExecuteNonQueryAsync(); }
        await Admin($"CREATE DATABASE \"{name}\"");
        try
        {
            await using var connection = new NpgsqlConnection(new NpgsqlConnectionStringBuilder(server.ConnectionString) { Database = name }.ConnectionString);
            await connection.OpenAsync();
            await using var transaction = await connection.BeginTransactionAsync();
            async Task Execute(string sql) { await using var c = new NpgsqlCommand(sql, connection, transaction); await c.ExecuteNonQueryAsync(); }
            async Task<T> Scalar<T>(string sql) { await using var c = new NpgsqlCommand(sql, connection, transaction); return (T)(await c.ExecuteScalarAsync())!; }
            foreach (var (table, id) in Tables)
                await Execute($"CREATE TABLE public.\"{table}\" (\"{id}\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, secret text); INSERT INTO public.\"{table}\" (secret) VALUES ('fixture'); GRANT ALL ON public.\"{table}\" TO PUBLIC;");
            await Execute("GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO PUBLIC");
            var operations = new SecurePaymentTables().UpOperations.Cast<SqlOperation>().ToList();
            // Valid on a plain PostgreSQL cluster, before API roles are introduced.
            foreach (var op in operations) await Execute(op.Sql);
            foreach (var role in new[] { "anon", "authenticated", "service_role" })
            {
                if (!await Scalar<bool>($"SELECT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='{role}')")) await Execute($"CREATE ROLE {role} NOLOGIN");
                foreach (var table in Tables.Keys) await Execute($"GRANT ALL ON public.\"{table}\" TO {role}");
                await Execute($"GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO {role}");
            }
            foreach (var op in operations) await Execute(op.Sql);
            // Reapplying does not restore access or change any receipt/refund data.
            foreach (var op in operations) await Execute(op.Sql);
            foreach (var table in Tables.Keys)
            {
                Assert.Equal(1L, await Scalar<long>($"SELECT count(*) FROM public.\"{table}\""));
                Assert.True(await Scalar<bool>($"SELECT relrowsecurity AND NOT relforcerowsecurity FROM pg_class WHERE oid='public.\"{table}\"'::regclass"));
                foreach (var role in new[] { "anon", "authenticated", "service_role" })
                {
                    Assert.False(await Scalar<bool>($"SELECT has_table_privilege('{role}', 'public.\"{table}\"', 'SELECT,INSERT,UPDATE,DELETE')"));
                    Assert.False(await Scalar<bool>($"SELECT has_sequence_privilege('{role}', pg_get_serial_sequence('public.\"{table}\"','{Tables[table]}'), 'USAGE,SELECT,UPDATE')"));
                    foreach (var sql in new[] { $"SELECT * FROM public.\"{table}\"", $"INSERT INTO public.\"{table}\" (secret) VALUES ('denied')",
                                 $"UPDATE public.\"{table}\" SET secret='denied'", $"DELETE FROM public.\"{table}\"" })
                    {
                        await transaction.SaveAsync("denied");
                        await Execute($"SET LOCAL ROLE {role}");
                        var error = await Assert.ThrowsAsync<PostgresException>(() => Execute(sql));
                        Assert.Equal("42501", error.SqlState);
                        await transaction.RollbackAsync("denied");
                    }
                }
            }
            await transaction.SaveAsync("column_grant");
            await Execute("GRANT SELECT (secret) ON public.\"PaymentRequests\" TO anon");
            var residual = await Assert.ThrowsAsync<PostgresException>(() => Execute(operations[0].Sql));
            Assert.Equal("P0001", residual.SqlState);
            await transaction.RollbackAsync("column_grant");
            // Any roles created above are transactional too, never retained on the local cluster.
            await transaction.RollbackAsync();
        }
        finally { await Admin($"DROP DATABASE \"{name}\" WITH (FORCE)"); }
    }
}
